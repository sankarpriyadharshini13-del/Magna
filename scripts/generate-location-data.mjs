// Regenerates the bundled country and Indian state lists from the country-state-city dataset, so the
// instant suggestions in the enquiry forms always match the state / city API routes.
// Run from the repo root: node scripts/generate-location-data.mjs
import fs from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { Country, State } = require("country-state-city");

const countries = Country.getAllCountries()
  .map((country) => ({ code: country.isoCode, name: country.name }))
  .sort((a, b) => a.name.localeCompare(b.name));

const countriesFile = `/**
 * Every country in the bundled country-state-city dataset, alphabetically sorted.
 * Generated by scripts/generate-location-data.mjs — re-run it after upgrading the package.
 * Served to the browser by GET /api/locations/countries; the same names are used by the
 * state / city lookups, so they always line up.
 */
export interface Country {
  /** ISO 3166-1 alpha-2 code, e.g. "IN". */
  code: string;
  name: string;
}

/** Country preselected on the enquiry forms. */
export const DEFAULT_COUNTRY_CODE = "IN";

export const COUNTRIES: Country[] = [
${countries.map((country) => `  { code: ${JSON.stringify(country.code)}, name: ${JSON.stringify(country.name)} },`).join("\n")}
];
`;

const states = State.getStatesOfCountry("IN")
  .map((state) => state.name)
  .sort((a, b) => a.localeCompare(b));

const statesFile = `/**
 * States and union territories of India, alphabetically sorted.
 * Generated by scripts/generate-location-data.mjs from the country-state-city dataset, so the
 * State field can suggest the right options without waiting on the network.
 */
export const INDIA_STATES: string[] = [
${states.map((state) => `  ${JSON.stringify(state)},`).join("\n")}
];
`;

fs.writeFileSync("data/countries.ts", countriesFile, "utf8");
fs.writeFileSync("data/india-states.ts", statesFile, "utf8");
console.log(`Wrote ${countries.length} countries and ${states.length} Indian states.`);
